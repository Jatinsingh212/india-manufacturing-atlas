/** Lucide component for an icon name (PascalCase or kebab-case); `fallback` when unknown. */
export function iconByName(name: string | null | undefined, fallback: LucideIcon = Boxes): LucideIcon {
  if (!name) return fallback;
  if (ICONS[name]) return ICONS[name];
  const pascal = name
    .split(/[-_\s]+/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
  return ICONS[pascal] ?? fallback;
}
